#!/usr/bin/env python3
"""Export browser reply data by exercising every native Lean selector residue.

Run from any working directory. Builds the pinned Lean source first; --check
compares the committed module without writing it. Uses only the Python standard
library so CI can verify the export before installing the application.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tomllib
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "lean/.lake/build/bin/indeed-core"
OUTPUT = ROOT / "web/replies.generated.js"
SOURCE_FILES = ("lean/Indeed.lean", "lean/Main.lean", "lean/lean-toolchain")


class ExportError(RuntimeError):
    """The compiled selector or generated module failed its export contract."""


def source_hashes(root: Path = ROOT) -> dict[str, str]:
    return {
        name: hashlib.sha256((root / name).read_bytes()).hexdigest()
        for name in SOURCE_FILES
    }


def run_core(core: Path, *args: str) -> Any:
    """Read the native protocol without reimplementing selection in Python."""
    try:
        result = subprocess.run(
            [str(core), *args], capture_output=True, encoding="utf-8",
            check=False, timeout=10,
        )
    except (OSError, UnicodeError, subprocess.TimeoutExpired) as error:
        raise ExportError(f"Could not execute the compiled Lean core: {error}") from error
    if result.returncode:
        raise ExportError(
            f"Lean core failed for {args!r}: {result.stderr.strip()[:300]}"
        )
    try:
        return json.loads(result.stdout)
    except (json.JSONDecodeError, RecursionError) as error:
        raise ExportError("Lean core returned invalid JSON.") from error


def collect_replies(core: Path = CORE) -> dict[str, list[str]]:
    """Get each exported string from `reply`, then compare it with `catalog`."""
    catalog = run_core(core, "catalog")
    if not isinstance(catalog, dict) or not catalog:
        raise ExportError("Native catalog must be a nonempty locale-to-pool object.")
    for locale, pool in catalog.items():
        if not isinstance(locale, str) or not locale:
            raise ExportError("Native locale codes must be nonempty strings.")
        if not isinstance(pool, list) or not pool or any(
            not isinstance(text, str) or not text for text in pool
        ):
            raise ExportError(f"Invalid native reply pool for {locale!r}.")

    exported: dict[str, list[str]] = {}
    for locale in sorted(catalog):
        pool = catalog[locale]
        replies = []
        for index in range(len(pool)):
            selected = run_core(core, "reply", locale, str(index))
            if (
                not isinstance(selected, dict)
                or selected.get("locale") != locale
                or type(selected.get("index")) is not int
                or selected["index"] != index
                or type(selected.get("pool_size")) is not int
                or selected["pool_size"] != len(pool)
                or selected.get("text") != pool[index]
            ):
                raise ExportError(
                    f"Native reply disagrees with its catalog at {locale}[{index}]."
                )
            # The exported value comes from the executable's selectReply path,
            # rather than copying a second hand-maintained response dictionary.
            replies.append(selected["text"])
        exported[locale] = replies
    return exported


def catalog_digest(catalog: dict[str, list[str]]) -> str:
    encoded = json.dumps(
        catalog, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def make_metadata(
    catalog: dict[str, list[str]], hashes: dict[str, str], root: Path = ROOT,
) -> dict[str, Any]:
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    return {
        "schema_version": 1,
        "package_version": project["project"]["version"],
        "lean_toolchain": (root / "lean/lean-toolchain").read_text(encoding="utf-8").strip(),
        "generator": "scripts/export_web.py",
        "source_sha256": hashes,
        "catalog_sha256": catalog_digest(catalog),
        "locale_count": len(catalog),
        "reply_count": sum(map(len, catalog.values())),
    }


def render_module(catalog: dict[str, list[str]], metadata: dict[str, Any]) -> str:
    """Stable UTF-8 ES module, independent of machine paths and build times."""
    data = json.dumps(catalog, ensure_ascii=False, sort_keys=True, indent=2)
    provenance = json.dumps(metadata, ensure_ascii=False, sort_keys=True, indent=2)
    return (
        "// Generated by scripts/export_web.py. Do not edit reply text here.\n"
        "// Values are exported from the compiled Lean selector; browser code is not formally proved.\n"
        f"const replyData = {data};\n\n"
        "for (const replies of Object.values(replyData)) Object.freeze(replies);\n"
        "export const replyCatalog = Object.freeze(replyData);\n\n"
        f"export const catalogMetadata = Object.freeze({provenance});\n"
    )


def check_or_write(output: Path, expected: str, check: bool) -> None:
    if check:
        if not output.is_file() or output.read_bytes() != expected.encode("utf-8"):
            raise ExportError(
                f"Browser catalog is missing or stale: {output}\n"
                "Regenerate it with: python scripts/export_web.py"
            )
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(expected.encode("utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the export without writing it.")
    args = parser.parse_args(argv)
    try:
        before = source_hashes()
        subprocess.run(["lake", "build"], cwd=ROOT / "lean", check=True)
        catalog = collect_replies()
        after = source_hashes()
        if before != after:
            raise ExportError("Lean sources changed during export; rerun the command.")
        metadata = make_metadata(catalog, after)
        check_or_write(OUTPUT, render_module(catalog, metadata), args.check)
    except (ExportError, OSError, subprocess.CalledProcessError) as error:
        print(f"export_web: {error}", file=sys.stderr)
        return 1
    verb = "Verified" if args.check else "Exported"
    print(f"{verb} {metadata['reply_count']} native replies across {metadata['locale_count']} locales: {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
